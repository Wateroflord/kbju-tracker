class GuideDish {
  final String name, about;
  final int portions;
  final List<(String, double)> items; // продукт из guideFoods, граммы
  final List<String> steps;
  const GuideDish(this.name, this.about, this.items, this.steps, {this.portions = 1});

  ({double kcal, double p, double f, double c, double grams}) get perPortion {
    var k = 0.0, p = 0.0, f = 0.0, c = 0.0, g = 0.0;
    for (final (n, grams) in items) {
      final x = guideFoods[n]!;
      k += x.kcal * grams / 100;
      p += x.p * grams / 100;
      f += x.f * grams / 100;
      c += x.c * grams / 100;
      g += grams;
    }
    return (kcal: k / portions, p: p / portions, f: f / portions, c: c / portions, grams: g / portions);
  }

  /// Как свой рецепт в приложении (тогда его можно добавлять в дневник).
  Recipe toRecipe(String id) => Recipe(
        id: id,
        name: name,
        portions: portions,
        items: [
          for (final (n, grams) in items)
            RecipeIngredient(
              name: n,
              grams: grams,
              kcal: guideFoods[n]!.kcal * grams / 100,
              protein: guideFoods[n]!.p * grams / 100,
              fat: guideFoods[n]!.f * grams / 100,
              carbs: guideFoods[n]!.c * grams / 100,
              fiber: guideFoods[n]!.fiber * grams / 100,
            ),
        ],
      );
}

