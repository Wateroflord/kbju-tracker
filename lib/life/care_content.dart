import 'package:flutter/material.dart';

import 'models.dart';

class CareSection {
  final String title;
  final List<String> bullets;
  const CareSection(this.title, this.bullets);
}

/// Рутина, которую можно добавить в привычки.
class CareRoutine {
  final String title;
  final HabitPeriod period;
  final String icon;
  const CareRoutine(this.title, this.period, this.icon);
}

class CareTopic {
  final String id;
  final String title;
  final String subtitle;
  final IconData icon;
  final String lead;
  final List<CareSection> sections;
  final List<CareRoutine> routines;
  const CareTopic({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.icon,
    required this.lead,
    required this.sections,
    this.routines = const [],
  });
}

class QuizOption {
  final String id;
  final String label;
  final String title;
  final List<String> advice;
  const QuizOption(this.id, this.label, this.title, this.advice);
}

