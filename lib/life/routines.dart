// Разминки и растяжка с таймером. Тексты — ключи перевода (русский).

class RoutineStep {
  final String name;
  final int seconds;
  final String hint;
  const RoutineStep(this.name, this.seconds, [this.hint = '']);
}

class Routine {
  final String id;
  final String title;
  final String desc;
  final String icon; // warmup | stretch | morning | back
  final List<RoutineStep> steps;
  const Routine(this.id, this.title, this.desc, this.icon, this.steps);

  int get totalSeconds => steps.fold(0, (s, e) => s + e.seconds) + steps.length * routinePause;
}

